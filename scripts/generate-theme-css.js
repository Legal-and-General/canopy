import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import postcss from 'postcss';

const directory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(directory, '..');
const tokenStyles = path.join(
  projectRoot,
  'node_modules/@legal-and-general/canopy-design-tokens/css',
);
const outputDirectory = path.join(projectRoot, 'dist/canopy/themes');
const selectorPattern = /^\.lg-mode-([A-Za-z0-9_-]+)\.lg-theme-([A-Za-z0-9_-]+)$/;

const parseStylesheet = async fileName =>
  postcss.parse(await fs.readFile(path.join(tokenStyles, fileName), 'utf8'));

export const extractThemes = root => {
  const themes = new Map();

  root.walkRules(rule => {
    if (rule.parent.type !== 'root') {
      return;
    }

    const match = rule.selector.trim().match(selectorPattern);

    if (!match) {
      return;
    }

    themes.set(`${match[1]}-${match[2]}`, rule.clone());
  });

  return themes;
};

export const assertThemesFound = themes => {
  if (!themes.size) {
    throw new Error('No component themes were found.');
  }
};

export const createDefaultTheme = (variables, themeProperties) => {
  const defaultTheme = postcss.rule({
    selector: '.lg-mode-blue.lg-theme-neutral',
  });

  variables.walkRules(':root', rule => {
    rule.walkDecls(declaration => {
      if (themeProperties.has(declaration.prop)) {
        defaultTheme.append(declaration.clone());
      }
    });
  });

  if (defaultTheme.nodes.length !== themeProperties.size) {
    throw new Error(
      `Expected ${themeProperties.size} default theme properties, found ${defaultTheme.nodes.length}`,
    );
  }

  return defaultTheme;
};

export const createStylesheet = rule => {
  const stylesheet = postcss.root();
  stylesheet.append(
    postcss.comment({ text: 'Generated by Canopy. Do not edit directly.' }),
    rule,
  );

  return `${stylesheet.toString()}\n`;
};

const main = async () => {
  const componentThemes = await parseStylesheet('component-themes.css');
  const themes = extractThemes(componentThemes);

  const themeProperties = new Set();
  const sourceTheme = themes.values().next().value;

  assertThemesFound(themes);

  sourceTheme.walkDecls(declaration => {
    themeProperties.add(declaration.prop);
  });

  const variables = await parseStylesheet('variables.css');
  themes.set(
    'blue-neutral',
    createDefaultTheme(variables, themeProperties),
  );

  await fs.rm(outputDirectory, { recursive: true, force: true });
  await fs.mkdir(outputDirectory, { recursive: true });

  await Promise.all(
    [ ...themes.entries() ].map(([ name, rule ]) =>
      fs.writeFile(
        path.join(outputDirectory, `${name}.css`),
        createStylesheet(rule),
      ),
    ),
  );

  console.log(`Generated ${themes.size} Canopy theme stylesheets.`);
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => {
    console.error(error);
    process.exitCode = 1;
  });
}